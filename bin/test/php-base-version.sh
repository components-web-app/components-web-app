#!/bin/sh
# The Dockerfile pulls the cwa-php-base of the template's own version, and the published stage holds nothing project-specific (#208).
# No image or network needed. Usage: bin/test/php-base-version.sh [Dockerfile] [create-cwa package.json]
set -eu

ROOT="$(dirname "$0")/../.."
DOCKERFILE="${1:-$ROOT/api/Dockerfile}"
PACKAGE="${2:-$ROOT/packages/create-cwa/package.json}"
IMAGE=ghcr.io/components-web-app/cwa-php-base
status=0
fail() { echo "FAIL: $*"; status=1; }

default=$(sed -n 's/^ARG CWA_PHP_BASE=//p' "$DOCKERFILE")
[ -n "$default" ] || fail "no 'ARG CWA_PHP_BASE=<image>' before the first FROM"

# A project generated by create-cwa has no packages/: it keeps whichever release it came from.
if [ -f "$PACKAGE" ]; then
	version=$(sed -n 's/^  "version": "\([^"]*\)".*/\1/p' "$PACKAGE" | head -1)
	[ -n "$version" ] || fail "no version in $PACKAGE"
	[ "$default" = "$IMAGE:$version" ] \
		|| fail "CWA_PHP_BASE defaults to '$default'; a release sets it to '$IMAGE:$version' with create-cwa's version"
else
	case "$default" in
		"$IMAGE":*) ;;
		*) echo "note: CWA_PHP_BASE defaults to '$default', not a published $IMAGE tag" ;;
	esac
fi

# The ARG must come before the first FROM, or FROM can't expand it.
first_from=$(grep -n '^FROM ' "$DOCKERFILE" | head -1 | cut -d: -f1)
arg_line=$(grep -n '^ARG CWA_PHP_BASE=' "$DOCKERFILE" | head -1 | cut -d: -f1)
[ -n "$arg_line" ] && [ -n "$first_from" ] && [ "$arg_line" -lt "$first_from" ] \
	|| fail "ARG CWA_PHP_BASE must come before the first FROM"

grep -qx 'FROM ${CWA_PHP_BASE} AS frankenphp_base' "$DOCKERFILE" \
	|| fail "frankenphp_base must start 'FROM \${CWA_PHP_BASE} AS frankenphp_base'"
grep -q '^FROM .* AS cwa_php_base$' "$DOCKERFILE" || fail "no cwa_php_base stage"

# The published stage may copy only the built binary and retry-fetch: a project's config must stay in its own build.
copies=$(awk '/^FROM /{in_stage = ($NF == "cwa_php_base")} in_stage && /^(COPY|ADD) /' "$DOCKERFILE")
echo "$copies" | while IFS= read -r line; do
	[ -n "$line" ] || continue
	case "$line" in
		"COPY --from=builder "*) ;;
		*" frankenphp/retry-fetch.sh /usr/local/bin/retry-fetch") ;;
		*) echo "FAIL: cwa_php_base copies a project file: $line"; exit 1 ;;
	esac
done || status=1

[ "$status" -eq 0 ] && echo "OK: CWA_PHP_BASE=$default; cwa_php_base holds no project files"
exit "$status"
